"""US 1960-1985 quarterly series for the L4 (m3) story step 「另一条岔路 B1：抽上来的水灌进河」 (故事读法, not a model replay).

Inputs (FRED downloads already in the repo, untrusted, read as data only; no new download was needed: they start in 1947 / 1954 / 1948 / 1966):
  data_src/real/fred/CPIAUCSL.csv      CPI-U, monthly index (observation_date, CPIAUCSL)
  data_src/real/fred/FEDFUNDS.csv      effective federal funds rate, monthly %   (observation_date, FEDFUNDS)
  data_src/real/fred/UNRATE.csv        unemployment rate, monthly %              (observation_date, UNRATE)
  data_src/real/fred/GFDEGDQ188S.csv   federal debt / GDP, quarterly %           (observation_date, GFDEGDQ188S)
Output: src/data/b1-story.js
  export const B1_STORY = { dates: ['1960Q1', ...], cpi: [...], ff: [...], u: [...], gd: [... | null], source, built }
  cpi = the quarter's average CPI index vs the same quarter a year earlier, minus 1 (物价比一年前); ff, u = quarterly means of the monthly
  values; gd = the quarterly value (null before 1966). All as shares (0.05 = 5%), rounded to 5 decimals.
  A quarter is written only when all three months are there (and, for cpi, the year-earlier quarter too).

Run: %USERPROFILE%\\.venvs\\dalio432\\Scripts\\python.exe -I tools/build_b1_story.py <repo root>
Only reads the two columns it needs from each file; every value goes through float(); nothing is evaluated.
tools/check_lessons.mjs re-reads the same CSVs and recomputes every value of the module.
"""
import csv
import datetime
import json
import sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else '.').resolve()
FRED = ROOT / 'data_src' / 'real' / 'fred'
OUT = ROOT / 'src' / 'data' / 'b1-story.js'
Y0, Y1 = 1960, 1985


def monthly(name, lo, hi):
    out = {}
    with (FRED / f'{name}.csv').open(encoding='utf-8', newline='') as f:
        for r in csv.DictReader(f):
            d = (r.get('observation_date') or '').strip()
            try:
                y, m = int(d[:4]), int(d[5:7])
                v = float(r.get(name))
            except (TypeError, ValueError):
                continue
            if 1940 <= y <= 2100 and 1 <= m <= 12 and lo < v < hi:
                out[(y, m)] = v
    return out


def quarterly(months):
    q = {}
    for (y, m), v in months.items():
        q.setdefault((y, (m - 1) // 3 + 1), []).append(v)
    return {k: sum(v) / 3 for k, v in q.items() if len(v) == 3}


def main():
    cpi_q = quarterly(monthly('CPIAUCSL', 0, 10000))
    ff_q = quarterly(monthly('FEDFUNDS', -5, 50))
    u_q = quarterly(monthly('UNRATE', 0, 50))
    gd = monthly('GFDEGDQ188S', 0, 500)            # quarterly file: one row per quarter, dated on its first month
    gd_q = {(y, (m - 1) // 3 + 1): v for (y, m), v in gd.items()}
    dates, cpi, ff, u, gdl = [], [], [], [], []
    for y in range(Y0, Y1 + 1):
        for q in range(1, 5):
            k, k0 = (y, q), (y - 1, q)
            if k not in cpi_q or k0 not in cpi_q or k not in ff_q or k not in u_q:
                raise SystemExit(f'missing data for {y}Q{q}')
            dates.append(f'{y}Q{q}')
            cpi.append(round(cpi_q[k] / cpi_q[k0] - 1, 5))
            ff.append(round(ff_q[k] / 100, 5))
            u.append(round(u_q[k] / 100, 5))
            gdl.append(round(gd_q[k] / 100, 5) if k in gd_q else None)
    stamp = datetime.date.fromtimestamp((FRED / 'CPIAUCSL.csv').stat().st_mtime).isoformat()
    obj = {
        'source': 'FRED CPIAUCSL, FEDFUNDS, UNRATE, GFDEGDQ188S (data_src/real/fred/*.csv)',
        'built': stamp,
        'dates': dates, 'cpi': cpi, 'ff': ff, 'u': u, 'gd': gdl,
    }
    body = ',\n  '.join(f'{k}: {json.dumps(v, ensure_ascii=False)}' for k, v in obj.items())
    OUT.write_text(
        '// AUTO-GENERATED by tools/build_b1_story.py - do not edit by hand.\n'
        '// US 1960-1985, quarterly: cpi = 物价比一年前 (quarter avg CPI-U vs the same quarter a year earlier), ff = federal funds rate,\n'
        '// u = unemployment, gd = federal debt / GDP (null before 1966). Shares (0.05 = 5%). For the L4 (m3) story step 「另一条岔路 B1」.\n'
        f'export const B1_STORY = {{\n  {body},\n}};\n', encoding='utf-8', newline='\n')
    print(f'wrote {OUT} ({len(dates)} quarters {dates[0]}..{dates[-1]})')


if __name__ == '__main__':
    main()
