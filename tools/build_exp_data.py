"""University of Michigan 1-year inflation expectations (FRED MICH, monthly, %) -> quarterly averages for the 「专题：预期」 lesson.

Input (untrusted download, read as data only): data_src/exp/MICH.csv
  https://fred.stlouisfed.org/graph/fredgraph.csv?id=MICH   (columns observation_date, MICH)
Output: src/data/exp-mich.js   export const MICH_Q = { dates: ['1978Q1', ...], mich: [0.052, ...] (share, not %), source, downloaded }
  A quarter is written only when all three months are there.

Run: %USERPROFILE%\\.venvs\\dalio432\\Scripts\\python.exe -I tools/build_exp_data.py <repo root>
Only reads the two columns it needs; every value goes through float(); nothing is evaluated.
"""
import csv
import datetime
import json
import sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else '.').resolve()
SRC = ROOT / 'data_src' / 'exp' / 'MICH.csv'
OUT = ROOT / 'src' / 'data' / 'exp-mich.js'


def main():
    months = {}
    with SRC.open(encoding='utf-8', newline='') as f:
        for r in csv.DictReader(f):
            d = (r.get('observation_date') or '').strip()
            try:
                y, m = int(d[:4]), int(d[5:7])
                v = float(r.get('MICH'))
            except (TypeError, ValueError):
                continue
            if 1970 <= y <= 2100 and 1 <= m <= 12 and -20 < v < 50:
                months[(y, m)] = v
    quarters = {}
    for (y, m), v in months.items():
        quarters.setdefault((y, (m - 1) // 3 + 1), []).append(v)
    keys = sorted(k for k, vs in quarters.items() if len(vs) == 3)
    dates = [f'{y}Q{q}' for y, q in keys]
    vals = [round(sum(quarters[k]) / 3 / 100, 5) for k in keys]
    stamp = datetime.date.fromtimestamp(SRC.stat().st_mtime).isoformat()
    body = (
        '// AUTO-GENERATED by tools/build_exp_data.py - do not edit by hand.\n'
        '// University of Michigan survey: expected price change over the next 12 months (households), quarterly mean of the monthly values.\n'
        f'export const MICH_Q = {{\n  source: "FRED MICH (data_src/exp/MICH.csv, downloaded {stamp})",\n'
        f'  dates: {json.dumps(dates)},\n  mich: {json.dumps(vals)},\n}};\n'
    )
    OUT.write_text(body, encoding='utf-8')
    print(len(dates), dates[0], dates[-1], 'max', max(vals))
    build_fx()


# Pegs that snapped (step 「汇率上的绳」): FRED daily DEXUSUK (USD per GBP) and DEXTHUS (THB per USD), 1990-2000 -> monthly means.
# Inputs (untrusted downloads): data_src/exp/DEXUSUK.csv, data_src/exp/DEXTHUS.csv  (observation_date, value; '' / '.' = no quote)
# Output: src/data/exp-fx.js   export const EXP_FX = { gbp: { months, usdPerGbp }, thb: { months, thbPerUsd }, source }
FX = [('gbp', 'DEXUSUK', 'usdPerGbp'), ('thb', 'DEXTHUS', 'thbPerUsd')]


def build_fx():
    out = {}
    for key, sid, field in FX:
        src = ROOT / 'data_src' / 'exp' / f'{sid}.csv'
        months = {}
        with src.open(encoding='utf-8', newline='') as f:
            for r in csv.DictReader(f):
                d = (r.get('observation_date') or '').strip()
                try:
                    y, m = int(d[:4]), int(d[5:7])
                    v = float(r.get(sid))
                except (TypeError, ValueError):
                    continue
                if 1990 <= y <= 2000 and 1 <= m <= 12 and 0 < v < 1000:
                    months.setdefault(f'{y}-{m:02d}', []).append(v)
        ks = sorted(months)
        out[key] = {'months': ks, field: [round(sum(months[k]) / len(months[k]), 4) for k in ks]}
    body = (
        '// AUTO-GENERATED by tools/build_exp_data.py - do not edit by hand.\n'
        '// FRED daily noon buying rates, monthly means: DEXUSUK (USD per GBP), DEXTHUS (THB per USD), 1990-2000.\n'
        f'export const EXP_FX = {{\n  source: "FRED DEXUSUK, DEXTHUS (data_src/exp/, daily -> monthly mean)",\n'
        f'  gbp: {json.dumps(out["gbp"])},\n  thb: {json.dumps(out["thb"])},\n}};\n'
    )
    (ROOT / 'src' / 'data' / 'exp-fx.js').write_text(body, encoding='utf-8')
    for key, sid, field in FX:
        o = out[key]
        print(key, len(o['months']), [(m, v) for m, v in zip(o['months'], o[field]) if m[:4] in ('1992', '1997', '1998')][:30])


if __name__ == '__main__':
    main()
