// node tools/freeze_log.mjs [--date YYYY-MM-DD] [--new-rules "what changed and why"] [--dry]
// 「从今天起冻结规则往后记」: the only clean test of the dials is going forward (tools/BACKTEST.md, BACKTEST-READOUT.md). This script keeps
// src/data/real/frozen-log.js: for every real quarter from the first frozen one on (USA 2026Q3, AUS 2026Q2: the last real quarters on
// 2026-10-30), the dial / lamp readings the app's CURRENT rules give (src/data/real/real-snapshot.js realTimeline = the same computeLamps /
// advanceCycles as the app), with the date they were recorded, the rules they were read with and a fingerprint of the data file.
//
// Run it after new real data arrives (tools/build_real_data.py). It
//   - APPENDS the quarters after each country's last logged quarter up to realLastDate(iso), recorded today;
//   - never rewrites a past row: old rows are copied verbatim (a quarter whose data were revised keeps the reading it had when recorded);
//   - refuses when src/engine/regimes.js changed since the last rules entry (sha256, CRLF -> LF) unless --new-rules "note" is given: the note
//     becomes a new rules entry and the rows recorded from then on point to it (old rows keep pointing to the old rules);
//   - refuses when the rules hash and a row's data fingerprint are unchanged but the reading is not (then something else that feeds the dials
//     changed, e.g. country-params.js thresholds or real-snapshot.js): that is a rule change too, so it needs --new-rules;
//   - refuses when a country's last real quarter is earlier than its last logged quarter.
// Checked by tools/check_backtest_view.mjs (rows = current readings where data and rules are unchanged; hash = regimes.js now).
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { realTimeline, realDates, realLastDate, REAL_ISOS } from '../src/data/real/real-snapshot.js';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const LOG_FILE = path.join(ROOT, 'src/data/real/frozen-log.js');
export const RULES_FILE = 'src/engine/regimes.js', PARAMS_FILE = 'src/data/country-params.js';
export const DATA_FILE = { USA: 'src/data/real/usa-real.js', AUS: 'src/data/real/aus-real.js' };

const lf = p => fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');
export const sha = p => createHash('sha256').update(lf(p)).digest('hex');
export const rulesHash = () => sha(RULES_FILE);
export const paramsHash = () => sha(PARAMS_FILE);
export const dataPrint = iso => sha(DATA_FILE[iso]).slice(0, 16);

/** the reading the current rules give for quarter q (the fields the log keeps) */
export function readingNow(iso, q) {
  const t = realDates(iso).indexOf(q);
  const T = realTimeline(iso)[t];
  if (!T) return null;
  const L = T.cycles.long, S = T.cycles.short;
  return {
    long: { stage: L.stage, label: L.label, fork: L.fork || null, pending: !!L.forkPending },
    short: { key: S.key, label: S.label, handoff: S.handoff === 'no' ? 'no' : null },
    lamps: Object.fromEntries(['credit', 'debtService', 'policy', 'valuation'].map(k => [k, T.lights[k] ? T.lights[k].level : null])),
  };
}
const READ_KEYS = ['long', 'short', 'lamps'];
export const sameReading = (row, r) => !!r && READ_KEYS.every(k => JSON.stringify(row[k]) === JSON.stringify(r[k]));

export async function loadLog() {
  if (!fs.existsSync(LOG_FILE)) return null;
  const m = await import(pathToFileURL(LOG_FILE).href + '?t=' + Date.now());
  return m.FROZEN_LOG;
}

/** deterministic file text: one row per line so a git diff shows exactly the appended quarters */
export function logFileText(log) {
  const J = x => JSON.stringify(x);
  const head = { generatedBy: log.generatedBy, about: log.about, frozenOn: log.frozenOn, rulesFile: log.rulesFile, paramsFile: log.paramsFile, dataFile: log.dataFile };
  const L = ['// GENERATED by tools/freeze_log.mjs: the frozen-rules log (append only). Do not edit by hand; past rows are never rewritten.',
    '// Each row = the dial / lamp readings the rules in force gave for that real quarter, recorded on recordedOn. tools/check_backtest_view.mjs checks it.',
    'export const FROZEN_LOG = {'];
  for (const [k, v] of Object.entries(head)) L.push(`  ${k}: ${J(v)},`);
  L.push('  rules: [');
  for (const r of log.rules) L.push(`    ${J(r)},`);
  L.push('  ],');
  L.push('  countries: {');
  for (const iso of Object.keys(log.countries)) {
    L.push(`    ${iso}: [`);
    for (const row of log.countries[iso]) L.push(`      ${J(row)},`);
    L.push('    ],');
  }
  L.push('  },');
  L.push('};');
  return L.join('\n') + '\n';
}

function localDate() { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; }

const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
  const arg = k => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
  const today = arg('--date') || localDate(), note = arg('--new-rules'), dry = process.argv.includes('--dry');
  if (!/^\d{4}-\d\d-\d\d$/.test(today)) { console.error('bad --date: ' + today); process.exit(2); }
  if (process.argv.includes('--new-rules') && !(note && note.trim())) { console.error('--new-rules needs a note: what changed and why'); process.exit(2); }
  const refuse = m => { console.error('REFUSED: ' + m); process.exit(1); };
  const hNow = rulesHash(), pNow = paramsHash();
  let log = await loadLog();
  const fresh = !log;
  if (fresh) {
    log = { generatedBy: 'tools/freeze_log.mjs', about: '从今天起冻结规则往后记：之后每季的读数按当时记下，事后不改',
      frozenOn: today, rulesFile: RULES_FILE, paramsFile: PARAMS_FILE, dataFile: DATA_FILE,
      rules: [{ id: 1, from: today, regimesSha256: hNow, paramsSha256: pNow, note: note || '首次冻结：' + today + ' 的规则' }], countries: {} };
    console.log(`new log: rules frozen on ${today}, regimes.js ${hNow.slice(0, 12)}`);
  }
  const before = JSON.stringify(log.countries);
  let cur = log.rules[log.rules.length - 1];
  if (!fresh) {
    const changed = cur.regimesSha256 !== hNow;
    // same rules file and same data, different reading -> something else that feeds the dials changed (thresholds, real-snapshot.js)
    const drift = [];
    if (!changed) for (const iso of Object.keys(log.countries)) for (const row of log.countries[iso])
      if (row.rules === cur.id && row.data === dataPrint(iso) && !sameReading(row, readingNow(iso, row.q))) drift.push(`${iso} ${row.q}`);
    if ((changed || drift.length) && !note)
      refuse(changed ? `${RULES_FILE} changed since the rules of ${cur.from} (${cur.regimesSha256.slice(0, 12)} -> ${hNow.slice(0, 12)}). ` +
        'Rows are read with the frozen rules. If the change is meant, run again with --new-rules "what changed and why".'
        : `same ${RULES_FILE} and same data, but the reading changed for ${drift.join(', ')} (country-params.js or real-snapshot.js?). ` +
        'That is a rule change: run again with --new-rules "what changed and why".');
    if (note) {
      if (!changed && !drift.length) refuse('--new-rules given, but nothing that feeds the readings changed');
      cur = { id: cur.id + 1, from: today, regimesSha256: hNow, paramsSha256: pNow, note };
      log.rules.push(cur);
      console.log(`new rules entry #${cur.id} from ${today}: ${note}`);
    }
  }
  let added = 0;
  for (const iso of REAL_ISOS) {
    const rows = (log.countries[iso] ||= []);
    const dates = realDates(iso), last = realLastDate(iso), iLast = dates.indexOf(last);
    const prev = rows.length ? dates.indexOf(rows[rows.length - 1].q) : iLast - 1;   // a new country starts at its last real quarter
    if (rows.length && prev < 0) refuse(`${iso}: logged quarter ${rows[rows.length - 1].q} is not on the real grid`);
    if (iLast < prev) refuse(`${iso}: the last real quarter ${last} is before the last logged one ${rows[rows.length - 1].q}`);
    for (let t = prev + 1; t <= iLast; t++) {
      const q = dates[t];
      rows.push({ q, recordedOn: today, rules: cur.id, data: dataPrint(iso), ...readingNow(iso, q) });
      added++;
      console.log(`${iso} ${q}: ${rows[rows.length - 1].long.label} | ${rows[rows.length - 1].short.label}`);
    }
    // report (never fix) past rows whose quarter now reads differently because the data were revised
    for (const row of rows) if (row.data !== dataPrint(iso) && !sameReading(row, readingNow(iso, row.q))) console.log(`note: ${iso} ${row.q} reads differently on today's data; kept as recorded on ${row.recordedOn}`);
  }
  // past rows: verbatim
  const old = JSON.parse(before);
  for (const iso of Object.keys(old)) if (JSON.stringify(old[iso]) !== JSON.stringify(log.countries[iso].slice(0, old[iso].length))) refuse(`${iso}: a past row would change`);
  if (!added && !fresh && !note) { console.log('nothing new: every country is logged up to its last real quarter'); process.exit(0); }
  if (dry) { console.log(`(dry run: ${added} row(s) would be added)`); process.exit(0); }
  fs.writeFileSync(LOG_FILE, logFileText(log));
  console.log(`wrote ${path.relative(ROOT, LOG_FILE)}: +${added} row(s)`);
}
