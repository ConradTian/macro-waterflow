// Cache-busting stamp for the static site (GitHub Pages caches every file ~10 min; a phone may keep an old gauge.js / gauge.css even longer).
// Run before every push:   node tools/stamp_version.mjs && node tools/check_version_stamp.mjs --static
//
// What it writes into index.html, free/index.html and blind/index.html (NOT v2/ — a frozen old version), between the BEGIN/END markers
// (re-running replaces the block, so it is idempotent; a file whose content did not change keeps its hash, so its URL stays cached):
//   1. <script type="importmap"> mapping every src/**/*.js module URL to the same URL + ?v=<hash>. Keys are written relative to the page
//      ("./src/ui/gauge.js" on /, "../src/ui/gauge.js" on /free/), so they resolve to exactly the absolute URLs the modules are imported by.
//      Static `import` and dynamic `import()` both go through the import map, so no import line in src/ needs a query string. A module's
//      import.meta.url then carries ?v=; `new URL('../x', import.meta.url)` drops the query, so the CSS loaders still build plain URLs.
//   2. ?v=<hash> on the page's own <link rel="stylesheet" href=".../assets/css/X.css"> and <script type="module" src=".../src/*.js"> tags
//      (an import map does not apply to <script src>, so the entry module is stamped in place).
//   3. a small inline script: window.MW_CSS_V = { 'gauge.css': '<hash>', ... } and two hooks that stamp the stylesheets the modules inject
//      later (gauge.js -> gauge.css, concepts.js -> causal.css, exp-gauge.js, asset-lake.js, fx-reactor.js, world-map.js, app.js real-mode,
//      lessons.js shock-lab, tabs/cycle.js), with zero edits to them:
//        - HTMLLinkElement.prototype.href setter: `l.href = '.../assets/css/X.css'` becomes '...X.css?v=<hash>' before the link is inserted,
//          so the unversioned URL is never requested at all;
//        - a MutationObserver on <head> as the fallback for setAttribute('href') / innerHTML: an added <link rel=stylesheet> for
//          assets/css/X.css without a query is rewritten to X.css?v=<hash>. It also drops an added stylesheet link whose (stamped) URL is
//          already linked: two loaders test `link[href$="X.css"]` (app.js real-mode.css, tabs/cycle.js cycle.css), which no longer matches
//          a stamped href, and a second copy appended at the end of <head> would change the cascade order.
//      The other loaders' "already loaded" tests split the href at '?' (gauge.js, concepts.js, lessons.js) or use includes / [href*=]
//      (asset-lake.js, exp-gauge.js, fx-reactor.js, world-map.js), so they keep working with ?v=.
// Hash = first 10 hex of sha256 over the file with CRLF -> LF (git's autocrlf checkout and the LF blob on GitHub give the same hash).
// usage: node tools/stamp_version.mjs [--quiet]
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, dirname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PAGES = ['index.html', 'free/index.html', 'blind/index.html'];
export const BEGIN = '<!-- BEGIN mw-version-stamp: generated by tools/stamp_version.mjs, do not edit by hand -->';
export const END = '<!-- END mw-version-stamp -->';

export const hashOf = buf => createHash('sha256').update(buf.toString('utf8').replace(/\r\n/g, '\n')).digest('hex').slice(0, 10);

function walk(dir, test, out = []) {
  for (const n of readdirSync(dir).sort()) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, test, out); else if (test(n)) out.push(p);
  }
  return out;
}
/** { modules: { 'src/ui/gauge.js': hash }, css: { 'gauge.css': hash } } — paths relative to the repo root, '/' separators */
export function collect() {
  const rel = p => relative(ROOT, p).split('\\').join('/');
  const modules = {}, css = {};
  for (const p of walk(join(ROOT, 'src'), n => n.endsWith('.js'))) modules[rel(p)] = hashOf(readFileSync(p));
  for (const n of readdirSync(join(ROOT, 'assets/css')).sort()) if (n.endsWith('.css')) css[n] = hashOf(readFileSync(join(ROOT, 'assets/css', n)));
  return { modules, css };
}
/** './' for index.html, '../' for free/index.html */
export const prefixOf = page => { const d = posix.dirname(page); return d === '.' ? './' : '../'.repeat(d.split('/').length); };

export function importMap(page, modules) {
  const pre = prefixOf(page), imports = {};
  for (const [f, h] of Object.entries(modules)) imports[pre + f] = `${pre}${f}?v=${h}`;
  return { imports };
}

// the inline CSS stamper (ES5-ish, runs before any module); PRE = the page's path to the site root
function cssScript(pre, css) {
  return `<script>
/* stylesheets injected later by the modules get ?v=<hash> too (tools/stamp_version.mjs) */
(function () {
  var V = window.MW_CSS_V = ${JSON.stringify(css)};
  var BASE = new URL(${JSON.stringify(pre + 'assets/css/')}, document.baseURI).href;
  function stamp(href) {
    if (typeof href !== 'string' || href.indexOf(BASE) !== 0) return null;
    var f = href.slice(BASE.length);
    return /^[\\w.-]+\\.css$/.test(f) && V[f] ? href + '?v=' + V[f] : null;
  }
  function abs(v) { try { return new URL(v, document.baseURI).href; } catch (e) { return null; } }
  try {
    var d = Object.getOwnPropertyDescriptor(HTMLLinkElement.prototype, 'href');
    if (d && d.set && d.configurable) Object.defineProperty(HTMLLinkElement.prototype, 'href', {
      configurable: true, enumerable: d.enumerable, get: d.get,
      set: function (v) { d.set.call(this, stamp(abs(String(v))) || v); }
    });
  } catch (e) { /* the observer below still stamps */ }
  function fix(l) {
    if (!l || l.tagName !== 'LINK' || !/(^|\\s)stylesheet(\\s|$)/i.test(l.rel || '')) return;
    var s = stamp(l.href); if (s) l.setAttribute('href', s);
    var others = document.querySelectorAll('link[rel~="stylesheet"]');
    for (var i = 0; i < others.length; i++) if (others[i] !== l && others[i].href === l.href && l.href.indexOf('?v=') > 0) { l.remove(); return; }
  }
  new MutationObserver(function (ms) {
    for (var i = 0; i < ms.length; i++) {
      var m = ms[i];
      if (m.type === 'attributes') fix(m.target);
      else for (var j = 0; j < m.addedNodes.length; j++) fix(m.addedNodes[j]);
    }
  }).observe(document.head, { childList: true, subtree: true, attributes: true, attributeFilter: ['href', 'rel'] });
})();
</script>`;
}

export function block(page, { modules, css }, nl = '\n') {
  const map = JSON.stringify(importMap(page, modules), null, 1).replace(/\n\s*/g, '\n');   // one entry per line: readable diffs
  return [BEGIN, `<script type="importmap">`, map, `</script>`, cssScript(prefixOf(page), css), END].join('\n').replace(/\n/g, nl);
}

const strip = u => u.replace(/\?v=[0-9a-f]+$/, '');
/** the page text with the block (re)written and the static tags stamped */
export function stampPage(page, text, sums) {
  const nl = text.includes('\r\n') ? '\r\n' : '\n';
  const pre = prefixOf(page);
  // 1. drop an earlier block (with the line break after it)
  const b0 = text.indexOf(BEGIN), b1 = text.indexOf(END);
  if (b0 >= 0 && b1 > b0) text = text.slice(0, b0) + text.slice(b1 + END.length).replace(/^\r?\n/, '');
  // 2. static stylesheet links + module scripts
  text = text.replace(/(<link\b[^>]*\bhref=")([^"]+)(")/g, (all, a, href, z) => {
    const m = /assets\/css\/([\w.-]+\.css)$/.exec(strip(href));
    if (!m || !/rel="?stylesheet/.test(all) || strip(href) !== pre + 'assets/css/' + m[1]) return all;
    if (!sums.css[m[1]]) throw new Error(`${page}: links ${href}, which is not in assets/css`);
    return a + strip(href) + '?v=' + sums.css[m[1]] + z;
  });
  text = text.replace(/(<script\b[^>]*\btype="module"[^>]*\bsrc=")([^"]+)(")/g, (all, a, src, z) => {
    const u = strip(src);
    if (!u.startsWith(pre + 'src/')) return all;
    const f = u.slice(pre.length);
    if (!sums.modules[f]) throw new Error(`${page}: loads ${src}, which is not in src/`);
    return a + u + '?v=' + sums.modules[f] + z;
  });
  // 3. the block goes before the first stylesheet / script in <head> (an import map must come before every module script)
  const head = text.indexOf('</head>');
  if (head < 0) throw new Error(`${page}: no </head>`);
  const firstTag = text.slice(0, head).search(/<link\b[^>]*rel="?stylesheet|<script\b/);
  const at = firstTag >= 0 ? firstTag : head;
  return text.slice(0, at) + block(page, sums, nl) + nl + text.slice(at);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sums = collect();
  const quiet = process.argv.includes('--quiet');
  for (const page of PAGES) {
    const p = join(ROOT, page), before = readFileSync(p, 'utf8');
    const after = stampPage(page, before, sums);
    if (after !== before) writeFileSync(p, after);
    if (!quiet) console.log(`${page}: ${after === before ? 'unchanged' : 'stamped'} (${Object.keys(sums.modules).length} modules, ${Object.keys(sums.css).length} css)`);
  }
}
