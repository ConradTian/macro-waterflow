SPEC = [("USA", "美国", 1870), ("JPN", "日本", 1950), ("AUS", "澳洲", 1870), ("GBR", "英国", 1870), ("CHN", "中国", 1952)]
countries = []
for iso, name, a in SPEC:
    if iso == "CHN":
        g = owid[owid.entity == "China"].set_index("year").gdp.loc[a:].dropna()
        crises, src = [], "Maddison 2023（经 OWID）"
    else:
        jj = j[j.iso == iso].set_index("year").sort_index()
        g = jj.g.loc[a:2020].dropna()
        crises = [int(y) for y in jj.index[jj.crisisJST == 1] if a <= y <= 2020]
        if iso == "USA":
            ann = fred.groupby(fred.index.year).mean()
            ann = ann[(ann.index <= 2025)]          # full years only
            g = extend(g, ann)
            src = "JST 1870–2020，2021–2025 接 FRED 实际 GDP"
        else:
            o = owid[owid.code == iso].set_index("year").gdp.dropna()
            g = extend(g, o)
            src = f"JST 1870–2020{'，之后接 Maddison（经 OWID）' if g.index[-1] > 2020 else ''}"
    t = g.index.values.astype(float)
    y = np.log(g.values.astype(float))
    coef = np.polyfit(t, y, 1)
    dev = y - np.polyval(coef, t)
    long_ = hp_trend(dev, 100)
    pct = lambda v: [round(float((np.exp(x) - 1) * 100), 2) for x in v]
    countries.append({
        "iso": iso, "name": name, "years": [int(x) for x in t], "dev": pct(dev), "long": pct(long_),
        "trend": round(float((np.exp(coef[0]) - 1) * 100), 2), "crises": crises, "src": src,
        "now": {"mark": NOW[iso][0], "text": NOW[iso][1]},
    })
    print(name, int(t[0]), int(t[-1]), "trend", countries[-1]["trend"], "crises", crises)

# US quarterly short cycle
