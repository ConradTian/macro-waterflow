ROOT = Path(__file__).resolve().parent.parent
D432 = ROOT.parent / "dalio_432"
OUT = ROOT / "src" / "data" / "waves.js"


def hp_trend(x, lam):
    n = len(x)
    d = np.zeros((n - 2, n))
    for i in range(n - 2):
        d[i, i:i + 3] = [1, -2, 1]
    return np.linalg.solve(np.eye(n) + lam * d.T @ d, x)


j = pd.read_parquet(D432 / "data/jst_panel.parquet").reset_index()
j["g"] = j.rgdpmad * j["pop"]
owid = pd.read_csv(D432 / "closeout/data/owid_gdp.csv")
fred = pd.read_csv(D432 / "cache/fred_GDPC1_2026-10-26.csv", parse_dates=["observation_date"]).set_index("observation_date").GDPC1


def extend(g, growth):
    """Chain-link later years onto g using another source's growth rates."""
    g = g.copy()
    for y in growth.index:
        if y > g.index[-1] and (y - 1) in growth.index and (y - 1) in g.index:
            g.loc[y] = g.loc[y - 1] * growth.loc[y] / growth.loc[y - 1]
    return g


