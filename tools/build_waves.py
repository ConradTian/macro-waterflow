"""Build src/data/waves.js: Dalio's three lines from real data, five countries, plus the US quarterly short cycle.

Same method as dalio_432/closeout/scripts/dalio_waves.py (read-only source):
  log real GDP -> straight line (average growth over the window) -> deviation; long wave = HP(lambda=100) of the deviation.
  US quarterly: log GDPC1 minus HP(lambda=1600) trend, 1947Q1-2026Q2 fitted, 1995Q1-2025Q4 kept.
Run:  <venv>/Scripts/python.exe -I tools/build_waves.py
"""
